import "strings"

// ---------------------------------------------------------------- 托盘提示文本
//
// 悬浮提示只显示当前模式的温度墙 / 功耗墙，两行：
//
//	CPU 🌡85℃ ⚡38/38/45W
//	GPU 🌡87℃ ⚡50W
//
// 曾经还跟着两行风扇转速（🌀2990RPM），已经移除。原因不是显示麻烦，而是那条数据
// 要走 System/FanInfo：GCU 内部得先被「武装」才会推它，而开机时它常常武装失败且
// **不重试** —— 靠程序自己唤醒就得把官方控制台窗口拉到前台，代价比收益大。
// 详见 gcu.go 里主题常量那段说明。
//
// 温度/功耗这两行走的是 Fan/Status，一直很稳，不受上面那件事影响。

// 提示里每类读数前面挂的图标。集中定义，改样式时不用在两个文件之间来回找。
//
// 🌡 是**星平面**字符（UTF-16 里占两个码元，见 TestTipEmojiBudget），
// 所以往 szTip 里塞之前先量一下长度，别等 Shell 静默截断。
const (
	iconTemp = "🌡" // U+1F321 THERMOMETER
	iconWatt = "⚡" // U+26A1  HIGH VOLTAGE（基本平面，只占 1 个码元）

	// 温度单位用 U+2103 这一个码位，而不是 "°" + "C" 两个字符 ——
	// 后者在点阵/等宽字体里会被拆成两个不同宽度的字形，看着是歪的。
	unitTemp = "℃"
)

// composeTip 把限制信息的各行拼成最终的提示文本：
//
//	CPU 🌡85℃ ⚡38/38/45W
//	GPU 🌡87℃ ⚡50W
//
// 单独拆成函数是为了能脱离 App 直接测（szTip 的容量上限在这里量）。
// 「一行都没有」的情况由 App.tooltip 先拦掉，不会走到这里。
func composeTip(rows []string) string {
	return strings.Join(rows, "\n")
}
